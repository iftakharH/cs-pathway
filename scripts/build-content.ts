import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { loadContent } from './lib/load-content'

const OUT_DIR = join(process.cwd(), 'src', 'content', 'generated')

const HEADER = `// Generated by scripts/build-content.ts. Do not edit by hand.\n// Source of truth: /content/*.yaml\n\n`

function emit(name: string, typeName: string, value: unknown, array = false) {
  const annotation = array ? `${typeName}[]` : typeName
  const body = `${HEADER}import type { ${typeName} } from '../schema'\n\nexport const ${name}: ${annotation} = ${JSON.stringify(value, null, 2)}\n`
  writeFileSync(join(OUT_DIR, `${name.toLowerCase()}.ts`), body, 'utf8')
}

function main() {
  const { content, errors, warnings } = loadContent()

  for (const warning of warnings) console.warn(`warning: ${warning}`)

  if (!content || errors.length > 0) {
    for (const error of errors) console.error(`error: ${error}`)
    console.error(`\nContent build failed with ${errors.length} error(s).`)
    process.exit(1)
  }

  mkdirSync(OUT_DIR, { recursive: true })

  emit('SITE', 'Site', content.site)
  emit('PHASES', 'Phase', content.phases, true)
  emit('SOURCES', 'Source', content.sources, true)
  emit('CLAIMS', 'Claim', content.claims, true)
  emit('MODULES', 'Module', content.modules, true)
  emit('CHEATSHEETS', 'CheatEntry', content.cheatsheets, true)
  emit('PLAYBOOK', 'PlaybookEntry', content.playbook, true)
  emit('HARNESSES', 'Harness', content.harnesses, true)
  emit('GLOSSARY', 'GlossaryTerm', content.glossary, true)
  emit('TRENDS', 'Trend', content.trends, true)

  const featuredCheat =
    content.cheatsheets.find((entry) => entry.id === 'git-undo') ?? content.cheatsheets[0]
  if (!featuredCheat) {
    console.error('error: at least one cheatsheet is required')
    process.exit(1)
  }

  emit('CATALOG', 'Catalog', {
    modules: content.modules.map((module) => ({
      id: module.id,
      phase: module.phase,
      order: module.order,
      title: module.title,
      summary: module.summary,
      estHours: module.estHours,
      prerequisites: module.prerequisites,
      cheatsheetIds: module.cheatsheetIds,
      quizCount: module.quiz.length,
      proofTitle: module.proof.title,
      proofBrief: module.proof.brief,
    })),
    cheatsheets: content.cheatsheets.map((entry) => ({
      id: entry.id,
      phase: entry.phase,
      topic: entry.topic,
      title: entry.title,
      whenToUse: entry.whenToUse,
      tags: entry.tags,
      tool: entry.tool,
      sourceUrl: entry.sourceUrl,
    })),
    featuredCheat,
  })

  const manifest = {
    generatedFrom: 'content/*.yaml',
    counts: {
      phases: content.phases.length,
      sources: content.sources.length,
      claims: content.claims.length,
      modules: content.modules.length,
      cheatsheets: content.cheatsheets.length,
      playbook: content.playbook.length,
      harnesses: content.harnesses.length,
      glossary: content.glossary.length,
      trends: content.trends.length,
    },
    moduleIds: content.modules.map((module) => module.id),
    cheatIds: content.cheatsheets.map((entry) => entry.id),
    claimIds: content.claims.map((claim) => claim.id),
    sourceIds: content.sources.map((source) => source.id),
    topicSlugs: [...new Set(content.cheatsheets.map((entry) => slugify(entry.topic)))],
    quizCount: content.modules.reduce((total, module) => total + module.quiz.length, 0),
    runnableSnippets: content.cheatsheets.reduce(
      (total, entry) => total + entry.snippets.filter((snippet) => snippet.runnable).length,
      0,
    ),
  }

  writeFileSync(
    join(OUT_DIR, 'manifest.ts'),
    `${HEADER}export const CONTENT_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const\n\nexport type ContentManifest = typeof CONTENT_MANIFEST\n`,
    'utf8',
  )

  const base = content.site.deployedUrl.replace(/\/$/, '')
  const routes = [
    '/',
    '/start',
    '/path',
    '/plan',
    '/cheatsheets',
    '/startup',
    '/tools',
    '/glossary',
    '/playbook',
    '/playbook/security',
    '/harnesses',
    '/trends',
    '/claims',
    '/sources',
    '/methodology',
    '/changelog',
    '/corrections',
    '/about',
    '/privacy',
    ...content.phases.map((phase) => `/phase/${phase.id}`),
    ...content.modules.map((module) => `/module/${module.id}`),
    ...content.cheatsheets.map((entry) => `/cheatsheet/${entry.id}`),
    ...manifest.topicSlugs.map((slug) => `/cheatsheets/${slug}`),
    ...content.playbook.filter((entry) => entry.id !== 'security').map((entry) => `/playbook/${entry.id}`),
  ]
  const sitemap = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...[...new Set(routes)].map((route) => `  <url><loc>${base}${route}</loc></url>`),
    '</urlset>',
    '',
  ].join('\n')
  writeFileSync(join(process.cwd(), 'public', 'sitemap.xml'), sitemap, 'utf8')

  console.log(
    `content: ${manifest.counts.modules} modules · ${manifest.counts.cheatsheets} cheatsheets · ` +
      `${manifest.counts.claims} claims · ${manifest.counts.sources} sources · ` +
      `${manifest.quizCount} quiz questions · ${manifest.runnableSnippets} executable snippets`,
  )
}

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

main()
